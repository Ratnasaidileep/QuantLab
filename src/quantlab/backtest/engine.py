
from collections.abc import Sequence
from dataclasses import dataclass
from itertools import pairwise

from quantlab.analytics.metrics import PerformanceMetrics, calculate_metrics
from quantlab.backtest.models import Trade, TradeSide
from quantlab.data.models import Bar
from quantlab.data.validation import validate_bar
from quantlab.portfolio.manager import Portfolio
from quantlab.strategy.base import Strategy
from quantlab.strategy.models import Signal
from quantlab.strategy.moving_average import MovingAverageCrossover


@dataclass(frozen=True)
class BacktestResult:
    bars_processed: int
    equity_curve: list[float]
    trades: list[Trade]
    final_cash: float
    final_equity: float
    total_pnl: float
    metrics: PerformanceMetrics | None


class Backtest:
    """Run a long-only strategy backtest.

    Signals are calculated using each bar's close.
    Trades are executed at the next bar's open.
    Commission and slippage are configurable.
    """

    def __init__(
        self,
        initial_cash: float,
        strategy: Strategy | None = None,
        commission_rate: float = 0.0,
        slippage_rate: float = 0.0,
        use_crossover: bool = False,
    ) -> None:
        if initial_cash < 0:
            raise ValueError("Initial cash cannot be negative.")

        if commission_rate < 0:
            raise ValueError("Commission rate cannot be negative.")

        if slippage_rate < 0:
            raise ValueError("Slippage rate cannot be negative.")

        self.initial_cash = initial_cash
        self.cash = initial_cash
        self.portfolio = Portfolio()
        self.strategy = strategy or MovingAverageCrossover(
            fast_period=2,
            slow_period=3,
        )
        self.commission_rate = commission_rate
        self.slippage_rate = slippage_rate
        self.use_crossover = use_crossover

    @property
    def position(self):
        return self.portfolio.position

    def run(self, bars: Sequence[Bar]) -> BacktestResult:
        # Validate all bars before changing backtest state.
        for bar in bars:
            validate_bar(bar)

        # Ensure bars are in chronological order.
        for previous, current in pairwise(bars):
            if current.timestamp <= previous.timestamp:
                raise ValueError(
                    "Bars must be ordered by strictly increasing timestamps."
                )

        # Reset state so each run is independent.
        self.cash = self.initial_cash
        self.portfolio = Portfolio()

        prices: list[float] = []
        equity_curve: list[float] = []
        trades: list[Trade] = []

        pending_signal = Signal.FLAT
        last_close: float | None = None

        for bar in bars:
            # Execute the signal generated by the previous bar
            # at the current bar's opening price.
            if pending_signal == Signal.LONG:
                if self.position.quantity == 0.0:
                    execution_price = bar.open * (1.0 + self.slippage_rate)
                    commission = execution_price * self.commission_rate
                    total_cost = execution_price + commission

                    if self.cash >= total_cost:
                        self.cash -= total_cost
                        self.portfolio.update(Signal.LONG, 1.0)

                        trades.append(
                            Trade(
                                timestamp=bar.timestamp,
                                side=TradeSide.BUY,
                                price=execution_price,
                                quantity=1.0,
                                commission=commission,
                            )
                        )

            elif (
                pending_signal != Signal.LONG
                and self.position.quantity > 0.0
            ):
                quantity = self.position.quantity
                execution_price = bar.open * (1.0 - self.slippage_rate)
                proceeds = execution_price * quantity
                commission = proceeds * self.commission_rate

                self.cash += proceeds - commission
                self.portfolio.update(Signal.FLAT, 0.0)

                trades.append(
                    Trade(
                        timestamp=bar.timestamp,
                        side=TradeSide.SELL,
                        price=execution_price,
                        quantity=quantity,
                        commission=commission,
                    )
                )

            # Generate the next signal from prices available so far.
            prices.append(bar.close)

            if self.use_crossover:
                crossover_method = getattr(
                    self.strategy,
                    "generate_crossover_signal",
                    None,
                )

                if not callable(crossover_method):
                    raise TypeError(
                        "The selected strategy does not support "
                        "crossover signals."
                    )

                signal = crossover_method(prices)
            else:
                signal = self.strategy.generate_signal(prices)

            # Store the signal for execution on the next bar.
            pending_signal = signal

            # Mark the portfolio to the current closing price.
            last_close = bar.close
            equity = self.cash + self.position.quantity * last_close
            equity_curve.append(equity)

        final_equity = (
            self.cash
            if last_close is None
            else self.cash + self.position.quantity * last_close
        )

        metrics = (
            calculate_metrics(
                initial_cash=self.initial_cash,
                equity_curve=equity_curve,
            )
            if equity_curve
            else None
        )

        return BacktestResult(
            bars_processed=len(bars),
            equity_curve=equity_curve,
            trades=trades,
            final_cash=self.cash,
            final_equity=final_equity,
            total_pnl=final_equity - self.initial_cash,
            metrics=metrics,
        )
