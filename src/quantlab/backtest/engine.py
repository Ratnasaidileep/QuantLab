
from collections.abc import Sequence
from dataclasses import dataclass
from itertools import pairwise

from quantlab.analytics.metrics import PerformanceMetrics, calculate_metrics
from quantlab.backtest.models import Trade, TradeSide
from quantlab.data.models import Bar
from quantlab.data.validation import validate_bar
from quantlab.portfolio.manager import Portfolio
from quantlab.strategy.base import Strategy
from quantlab.strategy.models import Signal
from quantlab.strategy.moving_average import MovingAverageCrossover


@dataclass(frozen=True)
class BacktestResult:
    bars_processed: int
    equity_curve: list[float]
    trades: list[Trade]
    final_cash: float
    final_equity: float
    total_pnl: float
    metrics: PerformanceMetrics | None


class Backtest:
    """Run a long-only strategy backtest.

    Signals are calculated using each bar's close.
    Trades are executed at the next bar's open.
    Commission and slippage are configurable.
    """

    def __init__(
        self,
        initial_cash: float,
        strategy: Strategy | None = None,
        commission_rate: float = 0.0,
        slippage_rate: float = 0.0,
        use_crossover: bool = False,
        sizing_mode: str = "unit",
        quantity_per_trade: float = 1.0,
        stop_loss_pct: float | None = None,
        take_profit_pct: float | None = None,
        trailing_stop_pct: float | None = None,
    ) -> None:
        if initial_cash < 0:
            raise ValueError("Initial cash cannot be negative.")

        if commission_rate < 0:
            raise ValueError("Commission rate cannot be negative.")

        if slippage_rate < 0:
            raise ValueError("Slippage rate cannot be negative.")

        if sizing_mode not in ("unit", "fixed_quantity", "all_in"):
            raise ValueError(
                f"Unsupported sizing mode '{sizing_mode}'. Supported modes: 'unit', 'fixed_quantity', 'all_in'."
            )

        if quantity_per_trade <= 0:
            raise ValueError("quantity_per_trade must be positive.")

        if stop_loss_pct is not None and stop_loss_pct <= 0:
            raise ValueError("stop_loss_pct must be strictly positive.")

        if take_profit_pct is not None and take_profit_pct <= 0:
            raise ValueError("take_profit_pct must be strictly positive.")

        if trailing_stop_pct is not None and trailing_stop_pct <= 0:
            raise ValueError("trailing_stop_pct must be strictly positive.")

        self.initial_cash = initial_cash
        self.cash = initial_cash
        self.portfolio = Portfolio()
        self.strategy = strategy or MovingAverageCrossover(
            fast_period=2,
            slow_period=3,
        )
        self.commission_rate = commission_rate
        self.slippage_rate = slippage_rate
        self.use_crossover = use_crossover
        self.sizing_mode = sizing_mode
        self.quantity_per_trade = quantity_per_trade
        self.stop_loss_pct = stop_loss_pct
        self.take_profit_pct = take_profit_pct
        self.trailing_stop_pct = trailing_stop_pct

    @property
    def position(self):
        return self.portfolio.position

    def run(self, bars: Sequence[Bar]) -> BacktestResult:
        # Validate all bars before changing backtest state.
        for bar in bars:
            validate_bar(bar)

        # Ensure bars are in chronological order.
        for previous, current in pairwise(bars):
            if current.timestamp <= previous.timestamp:
                raise ValueError(
                    "Bars must be ordered by strictly increasing timestamps."
                )

        # Reset state so each run is independent.
        self.cash = self.initial_cash
        self.portfolio = Portfolio()

        prices: list[float] = []
        equity_curve: list[float] = []
        trades: list[Trade] = []

        pending_signal = Signal.FLAT
        last_close: float | None = None
        entry_price: float | None = None
        peak_price: float | None = None
        cooldown_until_signal_reset = False

        for bar in bars:
            # Execute the signal generated by the previous bar
            # at the current bar's opening price.
            if pending_signal == Signal.LONG and not cooldown_until_signal_reset:
                if self.position.quantity == 0.0:
                    execution_price = bar.open * (1.0 + self.slippage_rate)
                    cost_per_unit = execution_price * (1.0 + self.commission_rate)

                    if self.sizing_mode == "unit":
                        trade_quantity = 1.0
                    elif self.sizing_mode == "fixed_quantity":
                        trade_quantity = self.quantity_per_trade
                    elif self.sizing_mode == "all_in":
                        trade_quantity = (
                            float(int(self.cash // cost_per_unit))
                            if cost_per_unit > 0
                            else 0.0
                        )

                    total_cost = trade_quantity * cost_per_unit
                    commission = (
                        trade_quantity * execution_price * self.commission_rate
                    )

                    if trade_quantity > 0.0 and self.cash >= total_cost:
                        self.cash -= total_cost
                        self.portfolio.update(Signal.LONG, trade_quantity)
                        entry_price = execution_price
                        peak_price = bar.open

                        trades.append(
                            Trade(
                                timestamp=bar.timestamp,
                                side=TradeSide.BUY,
                                price=execution_price,
                                quantity=trade_quantity,
                                commission=commission,
                            )
                        )

            elif (
                pending_signal != Signal.LONG
                and self.position.quantity > 0.0
            ):
                quantity = self.position.quantity
                execution_price = bar.open * (1.0 - self.slippage_rate)
                proceeds = execution_price * quantity
                commission = proceeds * self.commission_rate

                self.cash += proceeds - commission
                self.portfolio.update(Signal.FLAT, 0.0)
                entry_price = None
                peak_price = None

                trades.append(
                    Trade(
                        timestamp=bar.timestamp,
                        side=TradeSide.SELL,
                        price=execution_price,
                        quantity=quantity,
                        commission=commission,
                        exit_reason="signal",
                    )
                )

            # Intraday Stop-Loss and Take-Profit risk monitoring
            if self.position.quantity > 0.0 and entry_price is not None:
                current_peak = peak_price if peak_price is not None else bar.open

                sl_barrier: float | None = None
                if self.stop_loss_pct is not None:
                    sl_barrier = entry_price * (1.0 - self.stop_loss_pct)
                if self.trailing_stop_pct is not None:
                    trail_barrier = current_peak * (1.0 - self.trailing_stop_pct)
                    sl_barrier = (
                        max(sl_barrier, trail_barrier)
                        if sl_barrier is not None
                        else trail_barrier
                    )

                tp_barrier: float | None = None
                if self.take_profit_pct is not None:
                    tp_barrier = entry_price * (1.0 + self.take_profit_pct)

                is_sl_hit = sl_barrier is not None and bar.low <= sl_barrier
                is_tp_hit = tp_barrier is not None and bar.high >= tp_barrier

                if is_sl_hit:
                    # Conservative risk execution: stop-loss takes priority
                    exit_price = min(bar.open, sl_barrier) * (1.0 - self.slippage_rate)
                    quantity = self.position.quantity
                    proceeds = exit_price * quantity
                    commission = proceeds * self.commission_rate

                    self.cash += proceeds - commission
                    self.portfolio.update(Signal.FLAT, 0.0)
                    entry_price = None
                    peak_price = None
                    cooldown_until_signal_reset = True
                    pending_signal = Signal.FLAT

                    trades.append(
                        Trade(
                            timestamp=bar.timestamp,
                            side=TradeSide.SELL,
                            price=exit_price,
                            quantity=quantity,
                            commission=commission,
                            exit_reason="stop_loss",
                        )
                    )

                elif is_tp_hit:
                    exit_price = max(bar.open, tp_barrier) * (1.0 - self.slippage_rate)
                    quantity = self.position.quantity
                    proceeds = exit_price * quantity
                    commission = proceeds * self.commission_rate

                    self.cash += proceeds - commission
                    self.portfolio.update(Signal.FLAT, 0.0)
                    entry_price = None
                    peak_price = None
                    cooldown_until_signal_reset = True
                    pending_signal = Signal.FLAT

                    trades.append(
                        Trade(
                            timestamp=bar.timestamp,
                            side=TradeSide.SELL,
                            price=exit_price,
                            quantity=quantity,
                            commission=commission,
                            exit_reason="take_profit",
                        )
                    )
                else:
                    # Position survived intraday bar; update peak price for next bar
                    peak_price = max(current_peak, bar.high)

            # Generate the next signal from prices available so far.
            prices.append(bar.close)

            if self.use_crossover:
                crossover_method = getattr(
                    self.strategy,
                    "generate_crossover_signal",
                    None,
                )

                if not callable(crossover_method):
                    raise TypeError(
                        "The selected strategy does not support "
                        "crossover signals."
                    )

                signal = crossover_method(prices)
            else:
                signal = self.strategy.generate_signal(prices)

            # If stopped out or profit taken, reset cooldown once strategy goes flat/short
            if cooldown_until_signal_reset and signal != Signal.LONG:
                cooldown_until_signal_reset = False

            # Store the signal for execution on the next bar.
            pending_signal = signal if not cooldown_until_signal_reset else Signal.FLAT

            # Mark the portfolio to the current closing price.
            last_close = bar.close
            equity = self.cash + self.position.quantity * last_close
            equity_curve.append(equity)

        final_equity = (
            self.cash
            if last_close is None
            else self.cash + self.position.quantity * last_close
        )

        metrics = (
            calculate_metrics(
                initial_cash=self.initial_cash,
                equity_curve=equity_curve,
                trades=trades,
            )
            if equity_curve
            else None
        )

        return BacktestResult(
            bars_processed=len(bars),
            equity_curve=equity_curve,
            trades=trades,
            final_cash=self.cash,
            final_equity=final_equity,
            total_pnl=final_equity - self.initial_cash,
            metrics=metrics,
        )
